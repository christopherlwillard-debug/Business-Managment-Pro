import { pgTable, serial, text, timestamp, integer, numeric, boolean } from "drizzle-orm/pg-core";
import { createInsertSchema } from "drizzle-zod";
import { z } from "zod/v4";
import { jobsTable } from "./jobs";
import { recurringExpensesTable } from "./recurring-expenses";
import { businessTripsTable } from "./business-trips";

export const expensesTable = pgTable("expenses", {
  id: serial("id").primaryKey(),
  description: text("description").notNull(),
  amount: numeric("amount", { precision: 12, scale: 2 }).notNull(),
  category: text("category").notNull(),
  date: text("date").notNull(),
  vendor: text("vendor"),
  jobId: integer("job_id").references(() => jobsTable.id),
  subcontractorId: integer("subcontractor_id"),
  receiptUrl: text("receipt_url"),
  notes: text("notes"),
  recurringExpenseId: integer("recurring_expense_id").references(() => recurringExpensesTable.id, { onDelete: "set null" }),
  excludeFromNetProfit: boolean("exclude_from_net_profit").default(false).notNull(),
  businessLine: text("business_line"),
  businessId: integer("business_id"),
  jobSubHoursId: integer("job_sub_hours_id"),
  mileageImportId: integer("mileage_import_id"),
  countsTowardJobProfit: boolean("counts_toward_job_profit").default(true).notNull(),
  createdAt: timestamp("created_at").defaultNow().notNull(),
  tripId: integer("trip_id").references(() => businessTripsTable.id, { onDelete: "set null" }),
  overnightTravel: boolean("overnight_travel"),
  isPotentiallyNondeductible: boolean("is_potentially_nondeductible").default(false),
  mealTotal: numeric("meal_total", { precision: 12, scale: 2 }),
  deductibleAmount: numeric("deductible_amount", { precision: 12, scale: 2 }),
  nonDeductibleAmount: numeric("non_deductible_amount", { precision: 12, scale: 2 }),
  tipAmount: numeric("tip_amount", { precision: 12, scale: 2 }),
  taxAmount: numeric("tax_amount", { precision: 12, scale: 2 }),
  numPeople: integer("num_people"),
  paidBy: text("paid_by"),
  receiptStatus: text("receipt_status").default("uploaded"),
  receiptMissingExplanation: text("receipt_missing_explanation"),
  voidedAt: timestamp("voided_at"),
  voidReason: text("void_reason"),
  // Auto-linking: identifies expenses that were auto-generated by another feature.
  // source_type = "Material List" means the expense was created by a material list item.
  // Never rely on description/category matching to determine auto-managed status — use these fields.
  sourceType: text("source_type"),
  sourceId: integer("source_id"),
  // Marks a cash advance to a hourly-compensated subcontractor that was a pre-payment of wages
  // already fully captured in job_sub_hours auto-expenses (wage accruals). Setting this flag
  // excludes the advance from the Accounting route business-expense total to prevent double-
  // counting with the corresponding jsh auto-expenses. The advance still appears on the Expenses
  // page as a cash-flow record (it is a real cash outflow). Never set this flag on non-wage
  // payments (bonuses, materials reimbursements, etc.) — those belong in Accounting.
  isWageAdvance: boolean("is_wage_advance").default(false),
  // Explicit reporting-only classification; null keeps historical overhead unclassified.
  isSharedOverhead: boolean("is_shared_overhead"),
});

export const insertExpenseSchema = createInsertSchema(expensesTable).omit({ id: true, createdAt: true });
export type InsertExpense = z.infer<typeof insertExpenseSchema>;
export type Expense = typeof expensesTable.$inferSelect;
